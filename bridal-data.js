// ===== プロファイル導出（回答 → 生成パラメータ） =====
export function buildProfile(ans, diagnosis){
  const focusAreas = ans.focus && ans.focus.length ? ans.focus : ['waist','hip_leg'];
  const goals = ans.goal && ans.goal.length ? ans.goal : ['tone'];
  const careAreas = [];
  if (goals.includes('lymph')) careAreas.push('lymph');
  // 花嫁は姿勢が写真映えの要。明示がなくても薄く姿勢ケアを入れる
  careAreas.push('posture');
  const level = (ans.habit==='mid' || ans.habit==='active') ? 'intermediate' : 'beginner';
  const minutes = parseInt(ans.minutes||'20', 10);
  const days = parseInt(ans.days||'30', 10);
  const safety = ans.safety || [];
  const pregnant = safety.includes('preg');
  // 姿勢診断の結果（あれば）: その姿勢問題に効くヨガを優先配合する
  const diagnosisKeys = (diagnosis && Array.isArray(diagnosis.keys)) ? diagnosis.keys : [];
  const diagnosisType = (diagnosis && diagnosis.type) ? diagnosis.type : null;
  return { focusAreas, goals, careAreas, level, minutes, days, safety, pregnant, diagnosisKeys, diagnosisType };
}

