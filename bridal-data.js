// ===== プラン名（focus/goalから動的生成） =====
import { AREA_LABEL } from './bridal-engine.js';
export function planTitle(profile){
  const parts = profile.focusAreas.map(a => AREA_LABEL[a]).filter(Boolean);
  const head = parts.length>=3 ? '全身バランス' : parts.slice(0,2).join('と');
  const goalWord = profile.goals.includes('lymph') ? 'スッキリ'
                 : profile.goals.includes('posture') ? '美姿勢'
                 : '引き締め';
  return `${head}${parts.length>=3?'':'の'}${goalWord}プラン`;
}

